EQUIP = {
    "barbell": "Barra", "dumbbell": "Mancuernas", "cable": "Polea", "machine": "Máquina",
    "body only": "Peso corporal", "other": "Otro", "e-z curl bar": "Barra W",
    "exercise ball": "Pelota", None: "Peso corporal",
}

db = {e["id"]: e for e in json.load(open(sys.argv[1]))}
ids = {i for _, exs in DAYS for ex in exs for i in [ex[4], *ex[6]]}
missing = ids - set(db) | ids - set(ES)
assert not missing, missing

exercises = {}
for i in sorted(ids):
    e = db[i]
    exercises[i] = {
        "es": ES[i],
        "en": e["name"],
        "primary": [MUSCLES[m] for m in e["primaryMuscles"]],
        "secondary": [MUSCLES[m] for m in e["secondaryMuscles"]],
        "equipment": EQUIP.get(e["equipment"], e["equipment"]),
        "steps": e["instructions"],
        "images": e["images"],
    }

routine = [
    {"title": t, "items": [
        {"name": n, "sets": s, "reps": r, "note": c, "main": m, "tip": tip, "alts": alts}
        for n, s, r, c, m, tip, alts in exs]}
    for t, exs in DAYS
]

print("// Generado por tools/build.py — no editar a mano")
print("const ROUTINE = " + json.dumps(routine, ensure_ascii=False, indent=1) + ";")
print("const EXERCISES = " + json.dumps(exercises, ensure_ascii=False, indent=1) + ";")
